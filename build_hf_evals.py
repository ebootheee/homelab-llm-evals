#!/usr/bin/env python3
"""Build evals 6-7 (hard-reasoning-gpqa, instruction-following-ifeval) from Hugging Face.

Downloads rows via the HF datasets-server API (stdlib only, no `datasets` needed),
samples deterministically, stores the source rows in hf_hard_evals.json and appends
two evals to evals.yaml in the existing schema (id/category/difficulty/prompt/rubric),
so run_evals.py runs them unchanged.

Each eval is ONE prompt bundling 10 items, scored by 2 rubric criteria (items 1-5,
items 6-10). The gemma judge only sees the response, so each criterion carries the
answer key / constraint list it needs.

  eval 6: 10 GPQA-Diamond questions (Idavidrein/gpqa, gated: needs an HF token AND
          accepted terms). Falls back to 5 physics + 5 chemistry non-MMLU-sourced
          questions from TIGER-Lab/MMLU-Pro if GPQA is unavailable.
  eval 7: 10 google/IFEval prompts with 2-3 instructions each (judge-checkable ones).

Usage: python3 build_hf_evals.py [--seed N] [--force]
  --force  replace previously generated evals 6-7 (evals.yaml is backed up first)
Token: HF_TOKEN env, else huggingface_hub's stored token, else ~/.cache/huggingface/token.
"""
import argparse, json, os, random, shutil, string, sys, time, urllib.error, urllib.parse, urllib.request
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
EVALS_YAML = HERE / "evals.yaml"
OUT_JSON = HERE / "hf_hard_evals.json"
API = "https://datasets-server.huggingface.co"
MARKER = "  # --- HF-sourced evals 6-7 (generated by build_hf_evals.py; edit via --force rebuild) ---"
GPQA_ID, IFEVAL_ID = "hard-reasoning-gpqa", "instruction-following-ifeval"
N_ITEMS = 10


# ---------------------------------------------------------------- HF download

def hf_token():
    tok = os.environ.get("HF_TOKEN") or os.environ.get("HUGGING_FACE_HUB_TOKEN")
    if tok:
        return tok.strip()
    try:
        from huggingface_hub import get_token
        tok = get_token()
        if tok:
            return tok.strip()
    except Exception:
        pass
    p = Path.home() / ".cache" / "huggingface" / "token"
    return p.read_text().strip() if p.exists() else None


def api_get(endpoint, params, token, tries=4):
    url = f"{API}/{endpoint}?{urllib.parse.urlencode(params)}"
    headers = {"User-Agent": "eval-harness/1.0"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    last = None
    for i in range(tries):
        try:
            with urllib.request.urlopen(urllib.request.Request(url, headers=headers), timeout=60) as r:
                return json.loads(r.read().decode())
        except urllib.error.HTTPError as e:
            last = f"HTTP {e.code}: {e.read().decode(errors='replace')[:300]}"
            if e.code in (401, 403, 404):  # gated / no access / missing: retrying won't help
                break
        except Exception as e:
            last = f"{type(e).__name__}: {e}"
        time.sleep(2 * (i + 1))
    raise RuntimeError(f"{endpoint} {params.get('dataset')}/{params.get('config')}: {last}")


def fetch_all(dataset, config, split, token, where=None):
    """All rows of a split (or of a filter), paginated 100 at a time."""
    endpoint = "filter" if where else "rows"
    base = {"dataset": dataset, "config": config, "split": split}
    if where:
        base["where"] = where
    rows, offset, total = [], 0, None
    while total is None or offset < total:
        data = api_get(endpoint, {**base, "offset": offset, "length": 100}, token)
        total = data.get("num_rows_total", 0)
        batch = data.get("rows") or []
        if not batch:
            break
        for r in batch:
            if r.get("truncated_cells"):
                raise RuntimeError(f"{dataset} row {r['row_idx']} has truncated cells {r['truncated_cells']}")
            rows.append({"row_idx": r["row_idx"], **r["row"]})
        offset += len(batch)
    if not rows:
        raise RuntimeError(f"{dataset}/{config}/{split}: 0 rows (where={where!r})")
    return rows


# ---------------------------------------------------------------- eval 6: hard reasoning

def build_gpqa(rng, token):
    rows = fetch_all("Idavidrein/gpqa", "gpqa_diamond", "train", token)
    items = []
    for row in rng.sample(rows, N_ITEMS):
        opts = [(row["Correct Answer"].strip(), True)] + \
               [(row[f"Incorrect Answer {k}"].strip(), False) for k in (1, 2, 3)]
        rng.shuffle(opts)  # seeded: GPQA stores the correct answer first
        gold = string.ascii_uppercase[[c for _, c in opts].index(True)]
        items.append({"question": row["Question"].strip(), "options": [t for t, _ in opts],
                      "answer": gold, "source_row": row})
    return {"dataset": "Idavidrein/gpqa", "config": "gpqa_diamond", "split": "train",
            "rows_total": len(rows), "items": items}


def build_mmlu_pro(rng, token):
    items, totals = [], {}
    for cat in ("physics", "chemistry"):
        rows = fetch_all("TIGER-Lab/MMLU-Pro", "default", "test", token, where=f"\"category\"='{cat}'")
        # "Hard" = not inherited from original MMLU (scibench/theoremQA/stemez sources).
        hard = [r for r in rows if not str(r.get("src", "")).startswith("ori_mmlu")] or rows
        totals[cat] = {"rows": len(rows), "hard_pool": len(hard)}
        for row in rng.sample(hard, N_ITEMS // 2):
            items.append({"question": row["question"].strip(), "options": [o.strip() for o in row["options"]],
                          "answer": row["answer"].strip(), "source_row": row})
    rng.shuffle(items)
    return {"dataset": "TIGER-Lab/MMLU-Pro", "config": "default", "split": "test",
            "rows_total": totals, "items": items}


def gpqa_eval(src):
    blocks = []
    for n, it in enumerate(src["items"], 1):
        opts = "\n".join(f"  {string.ascii_uppercase[i]}) {o}" for i, o in enumerate(it["options"]))
        blocks.append(f"Question {n}:\n{it['question']}\n{opts}")
    prompt = (
        f"Answer the following {N_ITEMS} graduate-level multiple-choice science questions. "
        "Reason carefully but concisely (at most ~150 words per question). After each "
        "question's reasoning write one line exactly in the form `ANSWER n: X` (n = question "
        "number, X = a single option letter). Finish with a final block repeating all "
        f"{N_ITEMS} `ANSWER n: X` lines.\n\n" + "\n\n".join(blocks) + "\n")

    def crit(lo, hi):
        key = ", ".join(f"Q{n}={src['items'][n - 1]['answer']}" for n in range(lo, hi + 1))
        return (f"Correct answer letters for questions {lo}-{hi}. Answer key: {key}. Compare the "
                f"response's `ANSWER n: X` lines for questions {lo}-{hi} to the key (a missing, "
                "multi-letter, or self-contradictory answer counts as wrong). Score 2 only if all 5 "
                "match, 1 if 3 or 4 match, 0 if 2 or fewer match.")

    name = "GPQA-Diamond" if "gpqa" in src["dataset"] else "MMLU-Pro physics/chemistry (GPQA fallback)"
    return {
        "id": GPQA_ID,
        "category": f"hard science reasoning ({name}, HF {src['dataset']})",
        "difficulty": f"{N_ITEMS} expert-level multiple-choice questions sampled from {src['dataset']} "
                      "with a fixed seed; distractors are written to defeat pattern matching and the "
                      "answer must be committed as a single letter. Tests multi-step reasoning accuracy "
                      "under a strict answer format. Source rows in hf_hard_evals.json.",
        "prompt": prompt,
        "rubric": [crit(1, 5), crit(6, 10)],
    }


# ---------------------------------------------------------------- eval 7: instruction following

# Plain-English rendering of IFEval instruction ids, so the judge (which never sees
# the prompt) knows exactly what to check. Keys are the IFEval kwargs names.
IFEVAL_DESC = {
    "keywords:existence": "includes the keywords {keywords}",
    "keywords:frequency": "the word '{keyword}' appears {relation} {frequency} times",
    "keywords:forbidden_words": "never uses the words {forbidden_words}",
    "keywords:letter_frequency": "the letter '{letter}' appears {let_relation} {let_frequency} times",
    "language:response_language": "is written entirely in language '{language}' (ISO code), no other language",
    "length_constraints:number_sentences": "has {relation} {num_sentences} sentences",
    "length_constraints:number_paragraphs": "has exactly {num_paragraphs} paragraphs separated by the markdown divider ***",
    "length_constraints:number_words": "has {relation} {num_words} words",
    "length_constraints:nth_paragraph_first_word": "has exactly {num_paragraphs} paragraphs separated by blank lines, and paragraph {nth_paragraph} starts with the word '{first_word}'",
    "detectable_content:number_placeholders": "contains at least {num_placeholders} placeholders in square brackets like [address]",
    "detectable_content:postscript": "ends with a postscript starting with '{postscript_marker}'",
    "detectable_format:number_bullet_lists": "has exactly {num_bullets} markdown bullet points",
    "detectable_format:constrained_response": "is exactly one of: 'My answer is yes.', 'My answer is no.', 'My answer is maybe.'",
    "detectable_format:number_highlighted_sections": "highlights at least {num_highlights} sections with markdown, e.g. *highlighted section*",
    "detectable_format:multiple_sections": "has exactly {num_sections} sections, each beginning with '{section_spliter} N'",
    "detectable_format:json_format": "is entirely valid JSON (markdown code fences allowed)",
    "detectable_format:title": "includes a title wrapped in double angular brackets, e.g. <<title>>",
    "combination:two_responses": "gives two different responses separated by exactly six asterisks ******",
    "combination:repeat_prompt": "first repeats this request word for word, then answers: '{prompt_to_repeat}'",
    "startend:end_checker": "ends with the exact phrase '{end_phrase}' with nothing after it",
    "startend:quotation": "is entirely wrapped in double quotation marks",
    "change_case:capital_word_frequency": "has words in ALL CAPITALS appearing {capital_relation} {capital_frequency} times",
    "change_case:english_capital": "is entirely in English and in ALL CAPITAL letters",
    "change_case:english_lowercase": "is entirely in English and all lowercase, with no capital letters",
    "punctuation:no_comma": "contains no commas at all",
}
# Not judge-checkable by an LLM reading text (letter counting), or long enough to
# blow the candidates' 8192-token budget once 10 tasks share one reply.
IFEVAL_SKIP_IDS = {"keywords:letter_frequency"}
IFEVAL_MAX_WORDS_AT_LEAST = 300


def describe(iid, kw):
    kw = {k: v for k, v in (kw or {}).items() if v is not None}
    tmpl = IFEVAL_DESC.get(iid)
    if tmpl:
        try:
            return tmpl.format(**kw)
        except (KeyError, IndexError):
            pass
    return f"{iid} {json.dumps(kw, ensure_ascii=False)}"


def ifeval_ok(row):
    ids = row["instruction_id_list"]
    if not 2 <= len(ids) <= 3 or set(ids) & IFEVAL_SKIP_IDS:
        return False
    for iid, kw in zip(ids, row["kwargs"]):
        kw = kw or {}
        if (iid == "length_constraints:number_words" and kw.get("relation") == "at least"
                and (kw.get("num_words") or 0) > IFEVAL_MAX_WORDS_AT_LEAST):
            return False
    return True


def build_ifeval(rng, token):
    rows = fetch_all("google/IFEval", "default", "train", token)
    pool = [r for r in rows if ifeval_ok(r)]
    items = []
    for row in rng.sample(pool, N_ITEMS):
        items.append({"prompt": row["prompt"].strip(),
                      "constraints": [describe(i, k) for i, k in zip(row["instruction_id_list"], row["kwargs"])],
                      "source_row": row})
    return {"dataset": "google/IFEval", "config": "default", "split": "train",
            "rows_total": len(rows), "eligible_pool": len(pool), "items": items}


def ifeval_eval(src):
    blocks = [f"--- TASK {n} ---\n{it['prompt']}" for n, it in enumerate(src["items"], 1)]
    prompt = (
        f"Complete the following {N_ITEMS} independent tasks. Begin each task's response with a "
        "header line containing only `=== n ===` (n = task number), followed by that task's "
        "response. Every instruction in a task applies ONLY to the text under that task's header "
        "(the header line itself is exempt). Obey every instruction exactly and add no commentary "
        "outside the task sections.\n\n" + "\n\n".join(blocks) + "\n")

    def crit(lo, hi):
        parts = []
        for n in range(lo, hi + 1):
            cs = "; ".join(src["items"][n - 1]["constraints"])
            parts.append(f"Task {n} (text under '=== {n} ==='): {cs}.")
        return (f"All constraints obeyed in tasks {lo}-{hi}. Check each section against its "
                "constraints: " + " ".join(parts) + " Score 2 only if every listed constraint in "
                f"tasks {lo}-{hi} is obeyed exactly and every task is present, 1 if exactly one "
                "constraint is violated, 0 if two or more are violated or a task is missing.")

    return {
        "id": IFEVAL_ID,
        "category": "strict verifiable instruction following (IFEval, HF google/IFEval)",
        "difficulty": f"{N_ITEMS} IFEval prompts with 2-3 verifiable constraints each (case, length, "
                      "punctuation, keywords, format, start/end markers) answered in one reply with "
                      "per-task scoping. A single slip fails the constraint. Tests exact compliance over "
                      "helpfulness. Source rows in hf_hard_evals.json.",
        "prompt": prompt,
        "rubric": [crit(1, 5), crit(6, 10)],
    }


# ---------------------------------------------------------------- evals.yaml append

class _Dumper(yaml.SafeDumper):
    pass


def _str_rep(dumper, s):
    style = "|" if "\n" in s else None  # PyYAML falls back to quoted if | can't represent it
    return dumper.represent_scalar("tag:yaml.org,2002:str", s, style=style)


_Dumper.add_representer(str, _str_rep)


def append_evals(new_evals, force):
    text = EVALS_YAML.read_text()
    if MARKER in text:
        if not force:
            sys.exit(f"{EVALS_YAML.name} already has generated evals 6-7; rerun with --force to replace.")
        text = text[:text.index(MARKER)].rstrip("\n") + "\n"
    existing = {e["id"] for e in yaml.safe_load(text)["evals"]}
    clash = existing & {e["id"] for e in new_evals}
    if clash:
        sys.exit(f"ids {sorted(clash)} already exist in {EVALS_YAML.name} outside the generated block.")
    dumped = yaml.dump(new_evals, Dumper=_Dumper, sort_keys=False, allow_unicode=True,
                       default_flow_style=False, width=100)
    block = "\n".join(("  " + ln) if ln else ln for ln in dumped.splitlines())
    out = text.rstrip("\n") + "\n\n" + MARKER + "\n" + block + "\n"
    evals = yaml.safe_load(out)["evals"]  # validate before writing
    ids = [e["id"] for e in evals]
    assert len(ids) == len(set(ids)) and ids[-2:] == [GPQA_ID, IFEVAL_ID], ids
    assert all(isinstance(e.get("prompt"), str) and e.get("rubric") for e in evals)
    shutil.copy2(EVALS_YAML, EVALS_YAML.with_suffix(".yaml.bak"))
    EVALS_YAML.write_text(out)
    return ids


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--seed", type=int, default=20261121)
    ap.add_argument("--force", action="store_true", help="replace previously generated evals 6-7")
    args = ap.parse_args()
    token = hf_token()
    print(f"HF token: {'found' if token else 'none (GPQA is gated; will likely fall back)'}")

    fallback_reason = None
    try:
        reasoning = build_gpqa(random.Random(args.seed), token)
    except (RuntimeError, KeyError, ValueError) as e:  # gated/unavailable/schema drift
        fallback_reason = f"{type(e).__name__}: {e}"
        print(f"GPQA-Diamond unavailable ({e}); falling back to MMLU-Pro physics/chemistry")
        reasoning = build_mmlu_pro(random.Random(args.seed), token)
    reasoning["fallback_reason"] = fallback_reason
    ifeval = build_ifeval(random.Random(args.seed + 1), token)

    new_evals = [gpqa_eval(reasoning), ifeval_eval(ifeval)]
    OUT_JSON.write_text(json.dumps({
        "generated": time.strftime("%Y-%m-%d %H:%M:%S"), "seed": args.seed,
        "note": "GPQA content must not be republished in plain text online (dataset terms).",
        GPQA_ID: reasoning, IFEVAL_ID: ifeval,
    }, indent=2, ensure_ascii=False))
    ids = append_evals(new_evals, args.force)
    print(f"wrote {OUT_JSON.name}; {EVALS_YAML.name} now has {len(ids)} evals: {', '.join(ids)}")
    print(f"eval 6 source: {reasoning['dataset']}  answer key: "
          + " ".join(it["answer"] for it in reasoning["items"]))
    print(f"run: python3 run_evals.py --only {GPQA_ID} {IFEVAL_ID}")


if __name__ == "__main__":
    main()
